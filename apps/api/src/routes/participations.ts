/**
 * Participation of the players in a session (B-318): the staff's bulk entry
 * (status, minutes or minutes by period, contacts), its corrections, the player's own session
 * RPE within its window, and the lists. `srpe_au` is generated by the
 * database. Corrections of submitted values carry `changeReason` (ADR 0030);
 * the change history trigger refuses them without one.
 */

/** The values of a participation that a write decides. */
interface ParticipationValues {
  status: ParticipationStatus;
  minutes: number | null;
  periodMinutes: number[] | null;
  contactsN: number | null;
  rpe: number | null;
  rpeReportedAt: Date | null;
  rpeViaKiosk: boolean;
}

/**
 * The minutes and periods after a write (B-803, ADR 0091): periods set the
 * minutes as their sum; minutes alone are a total and clear the periods;
 * `periodMinutes: null` clears the periods and keeps (or sets) the total.
 */
function nextMinutes(
  current: ParticipationRow | undefined,
  input: {
    minutes?: number | null | undefined;
    periodMinutes?: readonly number[] | null | undefined;
  },
): Pick<ParticipationValues, 'minutes' | 'periodMinutes'> {
  if (input.periodMinutes !== undefined && input.periodMinutes !== null) {
    return {
      minutes: periodMinutesTotal(input.periodMinutes),
      periodMinutes: [...input.periodMinutes],
    };
  }
  if (input.periodMinutes === null || input.minutes !== undefined) {
    return {
      minutes: input.minutes === undefined ? (current?.minutes ?? null) : input.minutes,
      periodMinutes: null,
    };
  }
  return { minutes: current?.minutes ?? null, periodMinutes: current?.periodMinutes ?? null };
}

function samePeriods(a: readonly number[] | null, b: readonly number[] | null): boolean {
  if (a === null || b === null) return a === b;
  return a.length === b.length && a.every((minutes, index) => minutes === b[index]);
}

/**
 * The values after a staff write: omitted fields keep their value, `null`
 * clears them. Absent and unavailable carry no load: minutes, periods,
 * contacts and the RPE are cleared (clearing a submitted RPE is a correction).
 */
function nextValues(
  current: ParticipationRow | undefined,
  input: {
    status?: ParticipationStatus | undefined;
    minutes?: number | null | undefined;
    periodMinutes?: readonly number[] | null | undefined;
    contactsN?: number | null | undefined;
  },
): ParticipationValues {
  const status = input.status ?? current?.status ?? 'full';
  if (!participationCarriesLoad(status)) {
    return {
      status,
      minutes: null,
      periodMinutes: null,
      contactsN: null,
      rpe: null,
      rpeReportedAt: null,
      rpeViaKiosk: false,
    };
  }
  return {
    status,
    ...nextMinutes(current, input),
    contactsN: input.contactsN === undefined ? (current?.contactsN ?? null) : input.contactsN,
    rpe: current?.rpe ?? null,
    rpeReportedAt: current?.rpeReportedAt ?? null,
    rpeViaKiosk: current?.rpeViaKiosk ?? false,
  };
}

function sameValues(current: ParticipationRow, next: ParticipationValues): boolean {
  return (
    current.status === next.status &&
    current.minutes === next.minutes &&
    samePeriods(current.periodMinutes, next.periodMinutes) &&
    current.contactsN === next.contactsN &&
    current.rpe === next.rpe
  );
}

/** Facts of the players of a write, or `400` at the rows whose player the caller cannot see. */
async function factsOrUnknown(
  db: TenantDatabase,
  clubId: ClubId,
  session: SessionRow,
  playerIds: readonly PlayerId[],
  pathOf: (index: number) => (string | number)[],
): Promise<Map<PlayerId, PlayerFacts>> {
  const facts = await loadPlayerFacts(db, clubId, playerIds, session.sport);
  const unknown = playerIds.flatMap((id, index) => (facts.has(id) ? [] : [index]));
  if (unknown.length > 0) {
    throw new HttpError('validation_failed', 'Unknown player', {
      details: unknown.map((index) => ({
        path: pathOf(index),
        code: 'custom',
        message: 'No such player in this club',
      })),
    });
  }
  return facts;
}

async function authorizeRecord(
  permissions: RequestPermissions,
  facts: Map<PlayerId, PlayerFacts>,
): Promise<void> {
  for (const player of facts.values()) {
    await permissions.authorize('participation', 'record', { player });
  }
}

async function participationsBy(
  db: TenantDatabase,
  clubId: ClubId,
  where: SQL | undefined,
  lock = false,
): Promise<ParticipationRow[]> {
  const query = db
    .select(participationColumns)
    .from(participation)
    .where(and(eq(participation.clubId, clubId), where));
  return lock ? query.for('update') : query;
}

const PARTICIPATION_KEYS: KeysetSpec<
  ParticipationRow & { session: SummaryRow },
  'startsAt' | 'createdAt'
> = {
  fields: {
    startsAt: {
      column: trainingSession.startsAt,
      type: 'timestamp',
      value: (row) => row.session.startsAt,
    },
    createdAt: {
      column: participation.createdAt,
      type: 'timestamp',
      value: (row) => row.createdAt,
    },
  },
  id: { column: participation.id, value: (row) => row.id },
};

const MY_SESSION_KEYS: KeysetSpec<SummaryRow, 'startsAt'> = {
  fields: {
    startsAt: {
      column: trainingSession.startsAt,
      type: 'timestamp',
      value: (row) => row.startsAt,
    },
  },
  id: { column: trainingSession.id, value: (row) => row.id },
};

/**
 * The player who picked themselves on the club's kiosk (B-504) and its
 * facts, authorized for `rpe.kiosk_submit` (staff in their assignments, the
 * administration, with the player's data consent).
 */
async function kioskPlayer(
  db: TenantDatabase,
  permissions: RequestPermissions,
  clubId: ClubId,
  playerId: PlayerId,
  session: SessionRow,
): Promise<PlayerFacts> {
  // Who may not load on the kiosk is told so before learning whether the player exists.
  const scope = await permissions.listScope('rpe', 'kiosk_submit');
  if (scope.kind === 'none') throw new HttpError('forbidden', 'You are not allowed to do this');
  const facts = (await loadPlayerFacts(db, clubId, [playerId], session.sport)).get(playerId);
  if (facts === undefined) throw new HttpError('not_found', 'Player not found');
  await permissions.authorize('rpe', 'kiosk_submit', { player: facts });
  return facts;
}

/** The caller's own player and its facts; `403` for anyone who is not a player of the club. */
async function ownPlayer(
  db: TenantDatabase,
  permissions: RequestPermissions,
  clubId: ClubId,
  kind: 'rpe',
  action: 'read' | 'submit',
  session?: SessionRow,
): Promise<PlayerFacts> {
  const subject = await permissions.subject();
  const playerId = subject.playerId ?? null;
  if (subject.role !== 'player' || playerId === null) {
    // The matrix denies it (`role_denied` or `missing_target`): answered 403.
    await permissions.authorize(kind, action);
    throw new HttpError('forbidden', 'Only a player reports their RPE');
  }
  const facts = (await loadPlayerFacts(db, clubId, [playerId], session?.sport)).get(playerId);
  if (facts === undefined) throw new HttpError('forbidden', 'The player is not visible');
  await permissions.authorize(kind, action, { player: facts });
  return facts;
}

export function registerParticipationRoutes(app: FastifyInstance): void {
  registerEndpoint(app, recordParticipations, {
    transaction: true,
    changeReason: ({ body }) => body.changeReason,
    handler: async ({ params, body }, { db, permissions, auth: caller }) => {
      const { clubId } = caller.membership;
      const session = await readSession(db, clubId, params.trainingSessionId);
      await authorizeSession(permissions, session, 'read');
      assertSessionActive(session);
      assertParticipationFitsSport(session, body.rows, (index) => ['body', 'rows', index]);
      const playerIds = body.rows.map((row) => row.playerId);
      const facts = await factsOrUnknown(db, clubId, session, playerIds, (index) => [
        'body',
        'rows',
        index,
        'playerId',
      ]);
      await authorizeRecord(permissions, facts);
      // The rows of the batch, existing or not, as the offline push does (ADR 0050): two
      // batches that create the same participation wait for each other, not the unique key.
      await lockKeys(
        db,
        playerIds.map((playerId) => participationKey(session.id, playerId)),
      );

      const existing = new Map(
        (
          await participationsBy(
            db,
            clubId,
            and(
              eq(participation.trainingSessionId, session.id),
              inArray(participation.playerId, playerIds),
            ),
            true,
          )
        ).map((row) => [row.playerId, row]),
      );
      const applied = new Map(
        (
          await participationsBy(
            db,
            clubId,
            inArray(
              participation.clientUuid,
              body.rows.map((row) => row.clientUuid),
            ),
          )
        ).map((row) => [row.clientUuid, row]),
      );

      const items: {
        outcome: 'created' | 'updated' | 'unchanged' | 'replayed';
        row: ParticipationRow;
      }[] = [];
      for (const [index, input] of body.rows.entries()) {
        const previous = applied.get(input.clientUuid);
        if (previous !== undefined) {
          if (previous.trainingSessionId !== session.id || previous.playerId !== input.playerId) {
            throw new HttpError(
              'conflict',
              `Row ${String(index)}: this clientUuid was already used`,
            );
          }
          // The row of this clientUuid was created already: what it holds now.
          items.push({ outcome: 'replayed', row: previous });
          continue;
        }
        const current = existing.get(input.playerId);
        const next = nextValues(current, input);
        if (current === undefined) {
          const [created] = await db
            .insert(participation)
            .values({
              clubId,
              clientUuid: input.clientUuid,
              trainingSessionId: session.id,
              playerId: input.playerId,
              status: next.status,
              minutes: next.minutes,
              periodMinutes: next.periodMinutes,
              contactsN: next.contactsN,
              createdBy: caller.userId,
              updatedBy: caller.userId,
            })
            .returning(participationColumns);
          if (created === undefined)
            throw new Error('recordParticipations: insert returned no row');
          items.push({ outcome: 'created', row: created });
          continue;
        }
        if (sameValues(current, next)) {
          items.push({ outcome: 'unchanged', row: current });
          continue;
        }
        if (input.version !== undefined && input.version !== current.version) {
          throw new HttpError(
            'conflict',
            `Row ${String(index)}: the participation changed since it was read: read it again`,
          );
        }
        const [updated] = await db
          .update(participation)
          .set({ ...next, updatedBy: caller.userId })
          .where(and(eq(participation.clubId, clubId), eq(participation.id, current.id)))
          .returning(participationColumns);
        if (updated === undefined) throw new Error('recordParticipations: update returned no row');
        items.push({ outcome: 'updated', row: updated });
      }
      return {
        items: items.map(({ outcome, row }) => ({ outcome, participation: participationDto(row) })),
      };
    },
  });

  registerEndpoint(app, updateParticipation, {
    transaction: true,
    changeReason: ({ body }) => body.changeReason,
    handler: async ({ params, body }, { db, permissions, auth: caller }) => {
      const { clubId } = caller.membership;
      const [current] = await participationsBy(
        db,
        clubId,
        eq(participation.id, params.participationId),
      );
      if (current === undefined) throw new HttpError('not_found', 'Participation not found');
      const session = await readSession(db, clubId, current.trainingSessionId);
      await authorizeSession(permissions, session, 'read');
      const facts = await loadPlayerFacts(db, clubId, [current.playerId], session.sport);
      if (!facts.has(current.playerId)) throw new HttpError('not_found', 'Participation not found');
      await authorizeRecord(permissions, facts);
      assertSessionActive(session);
      assertParticipationFitsSport(session, [body], () => ['body']);
      const next = nextValues(current, body);
      const where = and(eq(participation.clubId, clubId), eq(participation.id, current.id));
      const row = await updateAtVersion({
        resource: 'Participation',
        update: async () =>
          (
            await db
              .update(participation)
              .set({ ...next, updatedBy: caller.userId })
              .where(and(where, versionMatches(participation.updatedAt, body.version)))
              .returning(participationColumns)
          )[0],
        exists: async () =>
          (await db.select({ id: participation.id }).from(participation).where(where)).length > 0,
      });
      return participationDto(row);
    },
  });

  registerEndpoint(app, listParticipations, {
    transaction: true,
    handler: async ({ query }, { db, permissions, auth: caller }) => {
      const { clubId } = caller.membership;
      const scope = await permissions.listScope('participation', 'read');
      const plan = keysetPage(PARTICIPATION_KEYS, query, {
        trainingSessionId: query.trainingSessionId,
        playerId: query.playerId,
        from: query.from,
        to: query.to,
      });
      if (scope.kind === 'none') return { items: [], nextCursor: null };
      let inScope: SQL | undefined;
      switch (scope.kind) {
        case 'club':
          break;
        case 'players':
          inScope = inArray(participation.playerId, [...scope.playerIds]);
          break;
        case 'assigned': {
          // The matrix scopes by the player's current categories (today, club time zone).
          const today = await clubToday(db);
          inScope = exists(
            db
              .select({ one: sql`1` })
              .from(playerCategory)
              .innerJoin(
                category,
                and(
                  eq(category.clubId, playerCategory.clubId),
                  eq(category.id, playerCategory.categoryId),
                ),
              )
              .where(
                and(
                  eq(playerCategory.clubId, participation.clubId),
                  eq(playerCategory.playerId, participation.playerId),
                  categoryCurrentOn(today),
                  or(
                    scope.categoryIds.length > 0
                      ? inArray(playerCategory.categoryId, [...scope.categoryIds])
                      : undefined,
                    scope.sports.length > 0
                      ? inArray(category.sport, [...scope.sports])
                      : undefined,
                  ),
                ),
              ),
          );
          break;
        }
        default:
          return { items: [], nextCursor: null };
      }
      const rows = await db
        .select({ ...participationColumns, session: summaryColumns })
        .from(participation)
        .innerJoin(
          trainingSession,
          and(
            eq(trainingSession.clubId, participation.clubId),
            eq(trainingSession.id, participation.trainingSessionId),
          ),
        )
        .where(
          and(
            eq(participation.clubId, clubId),
            inScope,
            query.trainingSessionId === undefined
              ? undefined
              : eq(participation.trainingSessionId, query.trainingSessionId),
            query.playerId === undefined ? undefined : eq(participation.playerId, query.playerId),
            query.from === undefined ? undefined : gte(trainingSession.localDate, query.from),
            query.to === undefined ? undefined : lte(trainingSession.localDate, query.to),
            plan.where,
          ),
        )
        .orderBy(...plan.orderBy)
        .limit(plan.limit);
      return plan.page(rows, (row): ParticipationListItem => ({
        ...participationDto(row),
        session: summaryDto(row.session),
      }));
    },
  });

  registerEndpoint(app, submitSessionRpe, {
    transaction: true,
    changeReason: ({ body }) => body.changeReason,
    handler: async ({ params, body }, { db, permissions, auth: caller, reply, recordedAt }) => {
      const { clubId } = caller.membership;
      const session = await readSession(db, clubId, params.trainingSessionId);
      const viaKiosk = body.playerId !== undefined;
      const me =
        body.playerId === undefined
          ? await ownPlayer(db, permissions, clubId, 'rpe', 'submit', session)
          : await kioskPlayer(db, permissions, clubId, body.playerId, session);
      // As the offline push (ADR 0050): an RPE that creates the participation waits for a
      // batch or another RPE that creates it at the same time, instead of hitting the unique key.
      await lockKeys(db, [participationKey(session.id, me.id)]);

      if (body.clientUuid !== undefined) {
        const [previous] = await participationsBy(
          db,
          clubId,
          eq(participation.clientUuid, body.clientUuid),
        );
        if (previous !== undefined) {
          if (previous.trainingSessionId !== session.id || previous.playerId !== me.id) {
            throw new HttpError('conflict', 'This clientUuid was already used');
          }
          markReplay(reply);
          return participationDto(previous);
        }
      }

      assertSessionActive(session);
      const window = rpeSubmissionWindow(session, await clubTimeZone(db, clubId));
      // Offline (ADR 0050): an RPE recorded inside the window counts when it syncs after it.
      const state = rpeWindowState(window, recordedAt ?? new Date());
      if (state !== 'open') {
        throw new HttpError(
          'conflict',
          state === 'not_open'
            ? 'The session has not started: the RPE is reported after it'
            : 'The RPE window of this session is closed',
        );
      }

      const [current] = await participationsBy(
        db,
        clubId,
        and(eq(participation.trainingSessionId, session.id), eq(participation.playerId, me.id)),
        true,
      );
      if (current === undefined) {
        if (session.categoryId === null) {
          throw new HttpError('forbidden', 'The session is not one of the player’s categories');
        }
        const [inCategory] = await db
          .select({ id: playerCategory.id })
          .from(playerCategory)
          .where(
            and(
              eq(playerCategory.clubId, clubId),
              eq(playerCategory.playerId, me.id),
              eq(playerCategory.categoryId, session.categoryId),
              categoryCurrentOn(session.localDate),
            ),
          )
          .limit(1);
        if (inCategory === undefined) {
          throw new HttpError('forbidden', 'The session is not one of the player’s categories');
        }
        // The player only reports the RPE: status and minutes are defaults the staff corrects
        // (ADR 0037), with no clock, so the staff's load wins over them however it syncs.
        const [created] = await withDefaultedFields(
          db,
          ['participation.status', 'participation.minutes'],
          () =>
            db
              .insert(participation)
              .values({
                clubId,
                ...(body.clientUuid !== undefined && { clientUuid: body.clientUuid }),
                trainingSessionId: session.id,
                playerId: me.id,
                status: 'full',
                minutes: session.plannedDurationMin,
                rpe: body.rpe,
                rpeReportedAt: sql`now()`,
                rpeViaKiosk: viaKiosk,
                createdBy: caller.userId,
                updatedBy: caller.userId,
              })
              .returning(participationColumns),
        );
        if (created === undefined) throw new Error('submitSessionRpe: insert returned no row');
        return participationDto(created);
      }
      if (!participationCarriesLoad(current.status)) {
        throw new HttpError(
          'conflict',
          'The staff recorded that the player did not take part in this session',
        );
      }
      if (viaKiosk && current.rpe !== null) {
        // The kiosk never corrects: the player does, from their own account, with a reason.
        throw new HttpError('conflict', 'The RPE of this session was already reported');
      }
      if (current.rpe === body.rpe) return participationDto(current);
      const [updated] = await db
        .update(participation)
        .set({
          rpe: body.rpe,
          rpeReportedAt: sql`now()`,
          rpeViaKiosk: viaKiosk,
          updatedBy: caller.userId,
        })
        .where(and(eq(participation.clubId, clubId), eq(participation.id, current.id)))
        .returning(participationColumns);
      if (updated === undefined) throw new Error('submitSessionRpe: update returned no row');
      return participationDto(updated);
    },
  });

  registerEndpoint(app, listMyTrainingSessions, {
    transaction: true,
    handler: async ({ query }, { db, permissions, auth: caller }) => {
      const { clubId } = caller.membership;
      const me = await ownPlayer(db, permissions, clubId, 'rpe', 'read');
      const plan = keysetPage(MY_SESSION_KEYS, query, { from: query.from, to: query.to });
      const mine = participation;
      const rows = await db
        .select(summaryColumns)
        .from(trainingSession)
        .where(
          and(
            eq(trainingSession.clubId, clubId),
            isNull(trainingSession.archivedAt),
            query.from === undefined ? undefined : gte(trainingSession.localDate, query.from),
            query.to === undefined ? undefined : lte(trainingSession.localDate, query.to),
            or(
              // Sessions of the player's categories on the session's day…
              exists(
                db
                  .select({ one: sql`1` })
                  .from(playerCategory)
                  .where(
                    and(
                      eq(playerCategory.clubId, trainingSession.clubId),
                      eq(playerCategory.playerId, me.id),
                      eq(playerCategory.categoryId, trainingSession.categoryId),
                      lte(playerCategory.validFrom, trainingSession.localDate),
                      or(
                        isNull(playerCategory.validTo),
                        sql`${playerCategory.validTo} > ${trainingSession.localDate}`,
                      ),
                    ),
                  ),
              ),
              // …and those the staff called them up to.
              exists(
                db
                  .select({ one: sql`1` })
                  .from(mine)
                  .where(
                    and(
                      eq(mine.clubId, trainingSession.clubId),
                      eq(mine.trainingSessionId, trainingSession.id),
                      eq(mine.playerId, me.id),
                    ),
                  ),
              ),
            ),
            plan.where,
          ),
        )
        .orderBy(...plan.orderBy)
        .limit(plan.limit);
      const page = plan.page(rows, (row) => row);
      const sessionIds = page.items.map((row) => row.id);
      const own = new Map(
        sessionIds.length === 0
          ? []
          : (
              await participationsBy(
                db,
                clubId,
                and(
                  eq(participation.playerId, me.id),
                  inArray(participation.trainingSessionId, sessionIds),
                ),
              )
            ).map((row) => [row.trainingSessionId, row]),
      );
      const timeZone = await clubTimeZone(db, clubId);
      const now = new Date();
      return {
        nextCursor: page.nextCursor,
        items: page.items.map((row): MyTrainingSession => {
          const window = rpeSubmissionWindow(row, timeZone);
          const current = own.get(row.id);
          return {
            session: summaryDto(row),
            participation: current === undefined ? null : participationDto(current),
            rpeWindow: {
              opensAt: window.opensAt.toISOString(),
              closesAt: window.closesAt.toISOString(),
            },
            canSubmitRpe:
              rpeWindowState(window, now) === 'open' &&
              (current === undefined || participationCarriesLoad(current.status)),
          };
        }),
      };
    },
  });
}
