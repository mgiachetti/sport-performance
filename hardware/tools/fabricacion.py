#!/usr/bin/env python3
"""Fabrication package of pod v0 for PCBWay (B-909): Gerbers, drill, pick and place, IPC-D-356, schematic, BOM.

Runs where ``kicad-cli`` and the ``pcbnew`` module are (the CI's KiCad image), from the repository root:

    python3 hardware/tools/fabricacion.py                 # writes hardware/pod-v0/salidas/pcbway/ and the zip
    python3 hardware/tools/fabricacion.py --salida DIR    # somewhere else

Everything comes from the committed board and schematic, with the drill/place origin at the lower-left corner
of the outline (``aux_axis_origin``), so the Gerbers, the drill files and the pick and place share it:

* ``gerbers/``: the 6 copper layers (F.Cu, In1–In4, B.Cu), masks, silkscreens, paste and the outline, with
  Protel extensions and the Gerber job file (X2); the drill files in Excellon (mm, PTH and NPTH apart) with
  their maps and report; and the IPC-D-356 netlist for the electrical test. Zones are refilled first.
* ``armado/``: the pick and place (CSV, mm, both sides, without the DNP places), the assembly BOM and the
  DNP list (``docs/hardware/cotizacion/``, generated by ``bom_pcbway.py``).
* ``pod-v0-esquematico.pdf`` and ``LEEME-PCBWAY.txt`` (board numbers taken from the board itself).
* ``pod-v0-pcbway.zip`` next to the folder, with all of it.

Then it checks the package and fails if anything is off: a missing or empty layer, a job file without the 6
copper layers, drill hits that do not match the board's holes, a pick and place that does not match the
assembly BOM (references, no repeats, DNP left out, inside the board), or a via whose hole is in an SMD pad or
less than ``VIA_PAD_GAP`` from it (the board is ordered without resin-filled vias, 27/11/2026). The CI runs it
and keeps the zip as an artifact.
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import shutil
import subprocess
import sys
import zipfile
from collections import Counter
from pathlib import Path

import pcbnew

ROOT = Path(__file__).resolve().parents[2]
POD = ROOT / "hardware" / "pod-v0"
PCB = POD / "pod-v0.kicad_pcb"
SCH = POD / "pod-v0.kicad_sch"
COTIZACION = ROOT / "docs" / "hardware" / "cotizacion"
BOM = COTIZACION / "bom-pod-v0.csv"
BOM_DNP = COTIZACION / "bom-pod-v0-sin-montar.csv"

COPPER = ["F.Cu", "In1.Cu", "In2.Cu", "In3.Cu", "In4.Cu", "B.Cu"]
OTHER = ["F.Mask", "B.Mask", "F.SilkS", "B.SilkS", "F.Paste", "B.Paste", "Edge.Cuts"]
# Gerber files kicad-cli writes for each layer (Protel extensions; inner layers keep their user names).
EXPECTED = ["F_Cu.gtl", "In1_Cu_GND.g1", "In2_Cu_SIG.g2", "In3_Cu_SIG.g3", "In4_Cu_GND.g4", "B_Cu.gbl",
            "F_Mask.gts", "B_Mask.gbs", "F_Silkscreen.gto", "B_Silkscreen.gbo", "F_Paste.gtp", "B_Paste.gbp",
            "Edge_Cuts.gm1", "job.gbrjob", "PTH.drl", "NPTH.drl"]
# Places in the pick and place that are not parts: the assembler aligns with them.
FIDUCIALS = re.compile(r"^FID\d+$")
# Outline corner the origin must sit on (KiCad coordinates, mm): lower-left of the 50 x 70 mm board.
ORIGIN_MM = (100.0, 170.0)
# Via hole to the copper of an SMD pad, any net (as VIA_PAD_GAP of rutear.py): with no via in a pad the board needs
# no resin filling and capping (POFV), about US$ 360 for 10 boards and US$ 5.4 a board at 100 (27/11/2026).
VIA_PAD_GAP = 0.15


def kicad(*args: str) -> None:
    subprocess.run(["kicad-cli", *args], check=True, cwd=POD, stdout=subprocess.DEVNULL)


def refs_of(path: Path) -> set[str]:
    with path.open(newline="", encoding="utf-8") as f:
        return {r.strip() for row in csv.DictReader(f) for r in row["Reference Designator"].split(",") if r.strip()}


def board_facts() -> dict:
    board = pcbnew.LoadBoard(str(PCB))
    origin = board.GetDesignSettings().GetAuxOrigin()
    holes = Counter()
    for track in board.GetTracks():
        if track.Type() == pcbnew.PCB_VIA_T:
            holes["PTH"] += 1
    sides, in_pads = {}, []
    vias = [t for t in board.GetTracks() if t.Type() == pcbnew.PCB_VIA_T]
    for fp in board.GetFootprints():
        for pad in fp.Pads():
            if pad.GetAttribute() != pcbnew.PAD_ATTRIB_SMD:
                continue
            layer = pcbnew.B_Cu if pad.IsOnLayer(pcbnew.B_Cu) else pcbnew.F_Cu
            shape = pad.GetEffectiveShape(layer)
            for via in vias:
                if shape.Collide(via.GetEffectiveHoleShape(), pcbnew.FromMM(VIA_PAD_GAP)):
                    in_pads.append(f"{fp.GetReference()}.{pad.GetNumber()}")
    for fp in board.GetFootprints():
        sides[fp.GetReference()] = "bottom" if fp.IsFlipped() else "top"
        for pad in fp.Pads():
            if pad.GetDrillSize().x > 0:
                holes["NPTH" if pad.GetAttribute() == pcbnew.PAD_ATTRIB_NPTH else "PTH"] += 1
    return {"origin": (pcbnew.ToMM(origin.x), pcbnew.ToMM(origin.y)), "holes": holes, "sides": sides,
            "vias": len(vias), "vias_in_pads": sorted(in_pads)}


def excellon_hits(path: Path) -> int:
    """Drill hits in an Excellon file: one coordinate line per hole (slots, ``G85``, count once)."""
    body = path.read_text().split("%", 2)[-1]
    return sum(1 for line in body.splitlines() if re.match(r"^X-?[\d.]+Y-?[\d.]+", line))


def generate(out: Path) -> None:
    gerbers, armado = out / "gerbers", out / "armado"
    gerbers.mkdir(parents=True)
    armado.mkdir()
    kicad("pcb", "export", "gerbers", "--check-zones", "--subtract-soldermask", "--use-drill-file-origin",
          "-l", ",".join(COPPER + OTHER), "-o", str(gerbers), PCB.name)
    kicad("pcb", "export", "drill", "-u", "mm", "--excellon-separate-th", "--excellon-oval-format", "alternate", "--drill-origin", "plot",
          "--generate-map", "--map-format", "gerberx2", "--generate-report",
          "--report-path", str(gerbers / "pod-v0-drill.rpt"), "-o", f"{gerbers}/", PCB.name)
    kicad("pcb", "export", "ipcd356", "-o", str(gerbers / "pod-v0.d356"), PCB.name)
    kicad("pcb", "export", "pos", "--format", "csv", "--units", "mm", "--side", "both", "--exclude-dnp",
          "--use-drill-file-origin", "-o", str(armado / "pod-v0-pick-and-place.csv"), PCB.name)
    kicad("sch", "export", "pdf", "-o", str(out / "pod-v0-esquematico.pdf"), SCH.name)
    kicad("pcb", "export", "stats", "--format", "json", "--units", "mm", "-o", str(out / "stats.json"), PCB.name)
    shutil.copy(BOM, armado / BOM.name)
    shutil.copy(BOM_DNP, armado / BOM_DNP.name)


def check(out: Path, facts: dict) -> list[str]:
    errors = []
    gerbers = out / "gerbers"
    if facts["vias_in_pads"]:
        errors.append(f"vias in (or within {VIA_PAD_GAP} mm of) SMD pads: {facts['vias_in_pads']}")
    if facts["origin"] != ORIGIN_MM:
        errors.append(f"drill/place origin at {facts['origin']}, not at the lower-left corner {ORIGIN_MM}")
    for name in EXPECTED:
        path = gerbers / f"pod-v0-{name}"
        if not path.is_file() or path.stat().st_size < 200:
            errors.append(f"missing or empty: {path.name}")
    job = gerbers / "pod-v0-job.gbrjob"
    if job.is_file():
        files = json.loads(job.read_text())["FilesAttributes"]
        copper = [f for f in files if f["FileFunction"].startswith("Copper")]
        if len(copper) != len(COPPER):
            errors.append(f"job file lists {len(copper)} copper layers, not {len(COPPER)}")
    for kind in ("PTH", "NPTH"):
        path = gerbers / f"pod-v0-{kind}.drl"
        if path.is_file() and excellon_hits(path) != facts["holes"][kind]:
            errors.append(f"{path.name}: {excellon_hits(path)} hits, the board has {facts['holes'][kind]} holes")

    mounted, dnp = refs_of(BOM), refs_of(BOM_DNP)
    with (out / "armado" / "pod-v0-pick-and-place.csv").open(newline="") as f:
        rows = list(csv.DictReader(f))
    pnp = {row["Ref"]: row for row in rows}
    if len(pnp) != len(rows):
        errors.append(f"repeated references in the pick and place: {sorted(r for r, n in Counter(r['Ref'] for r in rows).items() if n > 1)}")
    parts = {r for r in pnp if not FIDUCIALS.match(r)}
    if parts != mounted:
        errors.append(f"pick and place vs BOM: only in P&P {sorted(parts - mounted)}, "
                      f"only in BOM {sorted(mounted - parts)}")
    if parts & dnp:
        errors.append(f"DNP places in the pick and place: {sorted(parts & dnp)}")
    wrong = [r for r, row in pnp.items() if row["Side"] != facts["sides"].get(r)]
    if wrong:
        errors.append(f"wrong side in the pick and place: {sorted(wrong)}")
    outside = [r for r, row in pnp.items() if not (0 <= float(row["PosX"]) <= 50 and 0 <= float(row["PosY"]) <= 70)]
    if outside:
        errors.append(f"pick and place outside the 50 x 70 mm board (origin not applied?): {sorted(outside)}")
    return errors


def notes(out: Path, facts: dict) -> None:
    stats = json.loads((out / "stats.json").read_text())
    board = {k: float(str(v).split()[0]) for k, v in stats["board"].items()
             if k in ("width", "height", "min_track_width", "min_track_clearance", "board_thickness")}
    with (out / "armado" / "pod-v0-pick-and-place.csv").open(newline="") as f:
        sides = Counter(row["Side"] for row in csv.DictReader(f) if not FIDUCIALS.match(row["Ref"]))
    text = f"""pod v0 - fabrication package for PCBWay
========================================

Generated by hardware/tools/fabricacion.py from the committed KiCad 10 board. Details, questions and the
assembly notes: docs/hardware/cotizacion/pedido-pcbway.md.

Board
- 6 layers, FR4, 1.6 mm finished (stack-up in the board: {board['board_thickness']:g} mm); {board['width']:g} x {board['height']:g} mm, outline in Edge_Cuts.
- Layer order: F_Cu (L1), In1_Cu_GND (L2), In2_Cu_SIG (L3), In3_Cu_SIG (L4), In4_Cu_GND (L5), B_Cu (L6).
- Min track / space: {board['min_track_width']:g} / {board['min_track_clearance']:g} mm.
- {facts['vias']} through vias (0.5/0.2 and 0.6/0.3 mm), tented on both sides. None is in a pad: no resin
  filling and no via-in-pad process (POFV) needed.
- ENIG. Controlled impedance: 50 ohm CPWG on L1 (ref. L2) and L6 (ref. L5), 90 ohm differential pair (USB).
- Drill: Excellon in mm, PTH and NPTH in separate files. Electrical test netlist: pod-v0.d356.

Assembly (double-sided)
- {sides['top']} parts on top, {sides['bottom']} on the bottom ({sum(sides.values())} in total), same BOM for every board.
- Pick and place: armado/pod-v0-pick-and-place.csv (KiCad 10 CSV, mm, origin at the lower-left corner of the
  board as in the Gerbers; bottom side seen from the top, X not mirrored; DNP places left out). FID301-FID303
  are fiducials, not parts.
- BOM: armado/bom-pod-v0.csv; places not to mount: armado/bom-pod-v0-sin-montar.csv.
- AE201 (patch antenna, through-hole pin) is hand-soldered from the bottom AFTER reflow.
"""
    (out / "LEEME-PCBWAY.txt").write_text(text)


def zip_dir(out: Path) -> Path:
    target = out.with_name("pod-v0-pcbway.zip")
    target.unlink(missing_ok=True)
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as z:
        for path in sorted(out.rglob("*")):
            if path.is_file():
                z.write(path, path.relative_to(out))
    return target


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--salida", type=Path, default=POD / "salidas" / "pcbway", help="output folder")
    args = parser.parse_args()
    out = args.salida.resolve()
    if out.exists():
        # Only a folder this script wrote before (or an empty one) is replaced, never another one by mistake.
        if any(out.iterdir()) and not (out / "gerbers").is_dir():
            print(f"fabricacion: {out} exists and is not a previous package; choose another --salida", file=sys.stderr)
            return 1
        shutil.rmtree(out)
    facts = board_facts()
    generate(out)
    errors = check(out, facts)
    if errors:
        print("fabricacion: the package is not right:", *errors, sep="\n  ", file=sys.stderr)
        return 1
    notes(out, facts)
    (out / "stats.json").unlink()
    target = zip_dir(out)
    print(f"fabricacion: {target} ({target.stat().st_size // 1024} KiB), {facts['vias']} vias, "
          f"{facts['holes']['PTH']} PTH and {facts['holes']['NPTH']} NPTH holes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
