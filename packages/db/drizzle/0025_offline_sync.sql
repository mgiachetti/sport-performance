-- The push resolves a mutation (version, values and field clocks of its rows) and then runs its
-- handler. Under READ COMMITTED another push or an online edit could commit in between: an
-- older clock would overwrite a newer one, or a stale version would reject the newest clock.
-- The engine locks the rows first, in id order (no deadlock between two pushes on the same
-- rows), and only then reads them. FOR NO KEY UPDATE is the lock of an UPDATE: it waits for
-- the writers of the row and does not block the inserts that reference it (attempts of a
-- result). SECURITY DEFINER, so the lock does not depend on the UPDATE policy of the caller:
-- the engine loads the row under RLS before, and the handler answers the permissions.
CREATE FUNCTION "app"."sync_lock_rows"(target_collection text, ids uuid[])
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  club uuid := "app"."current_club_id"();
BEGIN
  IF "app"."current_role"() IS NULL OR club IS NULL THEN
    RAISE EXCEPTION 'sync_lock_rows needs a validated role' USING ERRCODE = 'insufficient_privilege';
  END IF;
  CASE target_collection
    WHEN 'wellness' THEN
      PERFORM 1 FROM "public"."wellness" t WHERE t.club_id = club AND t.id = ANY (ids)
        ORDER BY t.id FOR NO KEY UPDATE;
    WHEN 'participation' THEN
      PERFORM 1 FROM "public"."participation" t WHERE t.club_id = club AND t.id = ANY (ids)
        ORDER BY t.id FOR NO KEY UPDATE;
    WHEN 'test_result' THEN
      PERFORM 1 FROM "public"."test_result" t WHERE t.club_id = club AND t.id = ANY (ids)
        ORDER BY t.id FOR NO KEY UPDATE;
    ELSE
      RAISE EXCEPTION 'not a collection with field clocks' USING ERRCODE = 'invalid_parameter_value';
  END CASE;
END;
$$;
