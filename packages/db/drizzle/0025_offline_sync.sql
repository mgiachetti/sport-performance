-- Field clocks merged key by key: the later clock of each field wins.
CREATE FUNCTION "app"."sync_merge_clocks"(a jsonb, b jsonb) RETURNS jsonb
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT coalesce(pg_catalog.jsonb_object_agg(s.k, s.v), '{}'::jsonb)
    FROM (SELECT u.k, max(u.v COLLATE "C") AS v
            FROM (SELECT e.key AS k, e.value #>> '{}' AS v FROM pg_catalog.jsonb_each(coalesce(a, '{}'::jsonb)) e
                  UNION ALL
                  SELECT e.key, e.value #>> '{}' FROM pg_catalog.jsonb_each(coalesce(b, '{}'::jsonb)) e) u
           GROUP BY u.k) s
$$;
