-- Hybrid logical clocks (ADR 0015): `PPPPPPPPPPPPPPP-CCCCCC-node`, fixed width, so the binary
-- order of the text (COLLATE "C") is the order of the clocks (`compareHlc` of the domain).
-- The server stamps its own writes with its time, counter 0 and the node `server`.
CREATE FUNCTION "app"."server_hlc"() RETURNS text
LANGUAGE sql VOLATILE PARALLEL SAFE AS $$
  SELECT lpad(floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint::text, 15, '0') || '-000000-server'
$$;
