-- ─── Hand-written (ADR 0030): history triggers, append-only guard, RLS and grants ────
-- Change history of non-medical player data and sessions (B-305). The `medical` schema
-- is not tracked: it has its own append-only access log (0007, ADR 0029).
--
-- Rows are written only by `change_history_record`, an AFTER UPDATE OR DELETE trigger on
-- each tracked table (`CHANGE_TRACKED_TABLES` of the domain = the enum above). It runs as
-- the owner (SECURITY DEFINER): no connection role can INSERT, UPDATE or DELETE here, so
-- the history cannot be forged, edited or erased from the application.
--
-- Trigger arguments, per table:
--   0  where the player comes from: '' (no player: sessions), a column ('player_id'), or
--      '<fk column>:<parent table>' (the parent's player_id, for test_result_value).
--   1  "free" columns, as a text[] literal: lifecycle and derived columns whose changes
--      are recorded but never count as a correction (session status, worker-derived
--      maturation, generated load).
--   2  optional column that carries the reason of the change itself (void_reason).
--
-- What is recorded: the columns whose value changed (`IS DISTINCT FROM` on their JSON),
-- without the audit columns (`updated_at`, `updated_by`, `created_by`), with their old
-- and new values; a change of audit columns only (for example the ON DELETE SET NULL of
-- an author's account) records nothing. A delete records the whole row.
--
-- The reason: `app.change_reason` of the transaction (set_config(..., true), like the
-- tenant context), trimmed, at most 500 characters; for a void of a test_result_value
-- its `void_reason` when the setting is absent. A correction made by the API (the
-- session login is a member of sport_performance_app) needs one: a correction is a
-- delete, or an update that changes a non-free column whose previous value was not NULL
-- (a value already submitted). Filling an empty column (the player's RPE on the
-- participation the coach created, a void) is completion and needs no reason. The
-- worker (derived values, imports) and the owner (operators, referential actions) may
-- give one, but are not required to.
--
-- The author is `app.user_id` when it is an existing user, the role is the one validated
-- by app.current_role() (API only; `superadmin` only with its support access of the
-- transaction, 0007), the request id is app.current_request_id() (`app.request_id`).
CREATE FUNCTION "public"."change_history_record"() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, pg_temp AS $$
DECLARE
  audit_columns constant text[] := ARRAY['updated_at', 'updated_by', 'created_by'];
  player_source constant text := coalesce(TG_ARGV[0], '');
  free_columns constant text[] := coalesce(TG_ARGV[1], '{}')::text[];
  reason_column constant text := nullif(coalesce(TG_ARGV[2], ''), '');
  old_row constant jsonb := to_jsonb(OLD);
  new_row constant jsonb := CASE WHEN TG_OP = 'UPDATE' THEN to_jsonb(NEW) END;
  row_data constant jsonb := coalesce(new_row, old_row);
  club constant uuid := (row_data ->> 'club_id')::uuid;
  changed text[];
  old_values jsonb;
  new_values jsonb;
  is_correction boolean;
  change_source "public"."change_source";
  change_reason text;
  change_request_id text;
  author text;
  validated_role text;
  player uuid;
BEGIN
  SELECT array_agg(k ORDER BY k COLLATE "C"),
         jsonb_object_agg(k, old_row -> k),
         jsonb_object_agg(k, new_row -> k),
         bool_or(TG_OP = 'DELETE' OR (NOT k = ANY (free_columns) AND old_row -> k <> 'null'::jsonb))
    INTO changed, old_values, new_values, is_correction
    FROM jsonb_object_keys(old_row) AS k
   WHERE NOT k = ANY (audit_columns)
     AND (TG_OP = 'DELETE' OR (old_row -> k) IS DISTINCT FROM (new_row -> k));
  IF changed IS NULL THEN
    RETURN NULL;
  END IF;

  SELECT CASE
           WHEN r.rolsuper OR r.rolbypassrls THEN 'system'
           WHEN pg_has_role(r.oid, 'sport_performance_app', 'MEMBER') THEN 'app'
           WHEN pg_has_role(r.oid, 'sport_performance_worker', 'MEMBER') THEN 'worker'
           ELSE 'system'
         END::"public"."change_source"
    INTO change_source
    FROM pg_roles r WHERE r.rolname = session_user;

  change_reason := nullif(regexp_replace(coalesce(current_setting('app.change_reason', true), ''),
                                         '^\s+|\s+$', '', 'g'), '');
  IF change_reason IS NULL AND reason_column IS NOT NULL AND TG_OP = 'UPDATE' THEN
    change_reason := nullif(btrim(new_values ->> reason_column), '');
  END IF;
  IF change_reason IS NULL AND is_correction AND change_source = 'app' THEN
    RAISE EXCEPTION 'Changing submitted values of % requires a reason (app.change_reason)', TG_TABLE_NAME
      USING ERRCODE = 'check_violation', CONSTRAINT = 'change_history_reason_required',
            TABLE = TG_TABLE_NAME,
            HINT = 'Set it in the same transaction: select set_config(''app.change_reason'', <reason>, true)';
  END IF;
  IF char_length(change_reason) > 500 THEN
    RAISE EXCEPTION 'The reason of a change is at most 500 characters'
      USING ERRCODE = 'check_violation', CONSTRAINT = 'change_history_reason',
            TABLE = TG_TABLE_NAME;
  END IF;
  change_request_id := "app"."current_request_id"();

  SELECT u.id INTO author FROM "public"."user" u WHERE u.id = "app"."current_user_id"();
  IF change_source = 'app' THEN
    validated_role := "app"."current_role"();
  END IF;

  IF player_source = '' THEN
    player := NULL;
  ELSIF strpos(player_source, ':') > 0 THEN
    EXECUTE format('SELECT p.player_id FROM "public".%I p WHERE p.club_id = $1 AND p.id = $2',
                   split_part(player_source, ':', 2))
       INTO player
      USING club, (row_data ->> split_part(player_source, ':', 1))::uuid;
  ELSE
    player := (row_data ->> player_source)::uuid;
  END IF;

  INSERT INTO "public"."change_history"
    (club_id, created_by, table_name, record_id, player_id, operation, source, actor_role,
     changed_columns, old_values, new_values, reason, request_id)
  VALUES
    (club, author, TG_TABLE_NAME::"public"."change_tracked_table", (row_data ->> 'id')::uuid,
     player, lower(TG_OP)::"public"."change_operation", change_source, validated_role,
     changed, old_values, CASE WHEN TG_OP = 'UPDATE' THEN new_values END, change_reason,
     change_request_id);
  RETURN NULL;
END;
$$;
