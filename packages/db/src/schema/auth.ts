import { sql } from 'drizzle-orm';
import { boolean, check, index, pgTable, primaryKey, text, uniqueIndex } from 'drizzle-orm/pg-core';
import { timestamptz } from './columns.js';
import { deviceBrowserEnum, deviceOsEnum, sessionClientTypeEnum } from './enums.js';

/**
 * Global identity tables (ADR 0007, ADR 0010).
 *
 * They follow Better Auth's core schema (models `user`, `session`, `account`,
 * `verification`, `text` ids, the same field names) so B-309 can mount Better
 * Auth with its Drizzle adapter on top of these tables unchanged:
 *
 * ```ts
 * betterAuth({
 *   database: drizzleAdapter(db, { provider: 'pg', schema: authSchema }),
 *   advanced: { database: { generateId: 'uuid' } },
 *   user: { additionalFields: { isSuperadmin: { type: 'boolean', input: false } } },
 * });
 * ```
 *
 * The JS keys are Better Auth's field names (`emailVerified`, `userId`); the
 * SQL columns are `snake_case` like the rest of the schema. An integration
 * test checks these tables against Better Auth's `getAuthTables()` and signs a
 * user up through the adapter.
 *
 * Users are global: no `club_id`. What a club knows about a person lives in
 * `membership` and the club tables. RLS (ADR 0026): Better Auth reaches them
 * through `sport_performance_auth`; the API sees only the user itself and,
 * for staff, the members of the club; sessions, accounts and verifications
 * are invisible to it.
 */

/**
 * `text` primary key, as Better Auth expects, generated by the database as a
 * UUID: with `generateId: 'uuid'` Better Auth leaves the id to the database,
 * so user ids are UUIDs like every other id (the domain's `UserId`).
 */
function authId() {
  return text('id')
    .primaryKey()
    .default(sql`gen_random_uuid()::text`);
}

export const user = pgTable(
  'user',
  {
    id: authId(),
    name: text('name').notNull(),
    /**
     * Unique across the whole system: one account per person (ADR 0007).
     * Better Auth lowercases emails before writing them; `user_email_lower_key`
     * also rejects `Ana@x.com` next to `ana@x.com` for writes that bypass it
     * (imports, seeds, raw SQL).
     */
    email: text('email').notNull().unique(),
    emailVerified: boolean('email_verified').notNull().default(false),
    image: text('image'),
    createdAt: timestamptz('created_at').notNull().defaultNow(),
    updatedAt: timestamptz('updated_at').notNull().defaultNow(),
    /**
     * Global support role (ADR 0007): never a membership. Better Auth must
     * expose it as an additional field with `input: false`, so users cannot
     * grant it to themselves.
     */
    isSuperadmin: boolean('is_superadmin').notNull().default(false),
  },
  (t) => [uniqueIndex('user_email_lower_key').on(sql`lower(${t.email})`)],
);

export const session = pgTable(
  'session',
  {
    id: authId(),
    expiresAt: timestamptz('expires_at').notNull(),
    token: text('token').notNull().unique(),
    createdAt: timestamptz('created_at').notNull().defaultNow(),
    updatedAt: timestamptz('updated_at').notNull().defaultNow(),
    ipAddress: text('ip_address'),
    userAgent: text('user_agent'),
    userId: text('user_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    /**
     * Columns of "Sesiones activas" (B-333, ADR 0033), Better Auth additional
     * fields that only the API sets (`input: false`): how the session travels,
     * the coarse device derived from the `User-Agent` at sign-in (the raw
     * header and the IP are never stored) and when it was last used, which
     * the API refreshes at most every few minutes.
     */
    clientType: sessionClientTypeEnum('client_type').notNull(),
    deviceOs: deviceOsEnum('device_os'),
    deviceBrowser: deviceBrowserEnum('device_browser'),
    lastSeenAt: timestamptz('last_seen_at').notNull().defaultNow(),
  },
  (t) => [
    index('session_user_id_idx').on(t.userId),
    // The IP and the raw User-Agent of minors' devices are not kept (ADR 0033). Better Auth
    // writes '' when it has none.
    check('session_no_ip_address', sql`coalesce(${t.ipAddress}, '') = ''`),
    check('session_no_user_agent', sql`coalesce(${t.userAgent}, '') = ''`),
  ],
);

/**
 * Devices a user already signed in from (B-333, ADR 0033), to email "ingreso
 * nuevo" only for the others. The device id is a random UUID the device keeps
 * (an `HttpOnly` cookie on the web, secure storage in the app); only its
 * SHA-256 is stored. Unused for 400 days, a device is forgotten. RLS: only
 * Better Auth's role (`sport_performance_auth`).
 */
export const knownDevice = pgTable(
  'known_device',
  {
    userId: text('user_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    deviceHash: text('device_hash').notNull(),
    createdAt: timestamptz('created_at').notNull().defaultNow(),
    lastSeenAt: timestamptz('last_seen_at').notNull().defaultNow(),
  },
  (t) => [
    primaryKey({ name: 'known_device_pkey', columns: [t.userId, t.deviceHash] }),
    check('known_device_hash_format', sql`${t.deviceHash} ~ '^[0-9a-f]{64}$'`),
    index('known_device_last_seen_at_idx').on(t.lastSeenAt),
  ],
);

export const account = pgTable(
  'account',
  {
    id: authId(),
    accountId: text('account_id').notNull(),
    providerId: text('provider_id').notNull(),
    userId: text('user_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    accessToken: text('access_token'),
    refreshToken: text('refresh_token'),
    idToken: text('id_token'),
    accessTokenExpiresAt: timestamptz('access_token_expires_at'),
    refreshTokenExpiresAt: timestamptz('refresh_token_expires_at'),
    scope: text('scope'),
    password: text('password'),
    createdAt: timestamptz('created_at').notNull().defaultNow(),
    updatedAt: timestamptz('updated_at').notNull().defaultNow(),
  },
  (t) => [index('account_user_id_idx').on(t.userId)],
);

/** OTP codes and other short-lived verification values (email OTP, ADR 0010). */
export const verification = pgTable(
  'verification',
  {
    id: authId(),
    identifier: text('identifier').notNull(),
    value: text('value').notNull(),
    expiresAt: timestamptz('expires_at').notNull(),
    createdAt: timestamptz('created_at').notNull().defaultNow(),
    updatedAt: timestamptz('updated_at').notNull().defaultNow(),
  },
  (t) => [index('verification_identifier_idx').on(t.identifier)],
);

/** The tables Better Auth's Drizzle adapter needs, keyed by model name. */
export const authSchema = { user, session, account, verification } as const;
