import {
  CLUB_DATA_EXPORT_DATASETS,
  CLUB_DATA_EXPORT_ERROR_CODES,
  CLUB_DATA_EXPORT_FORMAT,
  CLUB_DATA_EXPORT_FORMAT_VERSION,
  CLUB_DATA_EXPORT_STATUSES,
  FILE_KIND_POLICIES,
  clubDataExportRangeProblems,
} from '@sport-performance/domain';
import { z } from 'zod';
import { defineEndpoint } from '../endpoint.js';
import { clientUuidSchema, sortQuerySchema } from '../primitives/conventions.js';
import { dateTimeSchema, localDateSchema } from '../primitives/dates.js';
import { idOf, userIdSchema } from '../primitives/ids.js';
import { pageOf, pageQuerySchema } from '../primitives/pagination.js';
import { fileIdSchema } from './clubs.js';
import { fileDownloadSchema } from './files.js';

/**
 * CSV export of the club's data (B-608, ADR 0072): asked by the
 * administration or the S&C staff, generated by the worker into a ZIP in the
 * bucket, downloaded with a short-lived signed URL.
 */

export const clubDataExportIdSchema = idOf('exportación de datos');

export const clubDataExportDatasetSchema = z.enum(CLUB_DATA_EXPORT_DATASETS).meta({
  id: 'ClubDataExportDataset',
  description:
    'Un CSV del ZIP: `players` (jugadores.csv, con la disponibilidad del día del pedido, nunca el motivo), `player_categories`, `anthropometry` (con la maduración), `test_results` (un valor por fila), `wellness`, `participations`, `external_loads` (actividades fuera del club informadas por el jugador), `load_daily` (sRPE, EWMA, ACWR, monotonía, con la parte externa aparte), `field_metrics`, `gym_sets` y `metrics` (el diccionario de métricas). Siempre van además `diccionario.csv` y `manifiesto.csv`.',
});

export const clubDataExportStatusSchema = z.enum([...CLUB_DATA_EXPORT_STATUSES, 'expired']).meta({
  id: 'ClubDataExportStatus',
  description:
    '`queued` (esperando), `running` (generándose), `ready` (lista para bajar), `failed` (con `errorCode`) o `expired` (el ZIP ya se borró: vence a los 7 días, o al suprimir un jugador/a que incluía).',
});

export const clubDataExportSchema = z
  .object({
    id: clubDataExportIdSchema,
    status: clubDataExportStatusSchema,
    requestedBy: userIdSchema
      .nullable()
      .meta({ description: 'Quién la pidió; `null` si después borró su cuenta.' }),
    requesterRole: z.enum(['sc', 'admin']),
    datasets: z.array(clubDataExportDatasetSchema),
    from: localDateSchema.nullable().meta({
      description:
        'Primer día del club de los datos con fecha (inclusive); `null` = desde el principio.',
    }),
    to: localDateSchema.nullable().meta({
      description: 'Último día del club de los datos con fecha (inclusive); `null` = hasta hoy.',
    }),
    requestedOn: localDateSchema.meta({
      description: 'Día del club del pedido: el de la disponibilidad y las categorías vigentes.',
    }),
    playerCount: z.int().nonnegative().meta({ description: 'Jugadores/as incluidos.' }),
    excludedPlayerCount: z.int().nonnegative().meta({
      description:
        'Jugadores/as del alcance que quedaron afuera por no tener consentimiento de datos vigente (sin nombres).',
    }),
    attempts: z.int().nonnegative(),
    rowCounts: z.record(z.string(), z.int().nonnegative()).nullable().meta({
      description: 'Filas por conjunto de datos, cuando está lista.',
    }),
    errorCode: z.enum(CLUB_DATA_EXPORT_ERROR_CODES).nullable().meta({
      description:
        'Por qué falló: `generation_failed`, `too_large` (achicar el rango o los conjuntos) o `storage_unavailable`.',
    }),
    file: z
      .object({
        id: fileIdSchema,
        fileName: z.string(),
        sizeBytes: z.int().positive(),
        expiresAt: dateTimeSchema.nullable(),
      })
      .nullable()
      .meta({ description: 'El ZIP, cuando está lista y no venció.' }),
    format: z.literal(CLUB_DATA_EXPORT_FORMAT),
    formatVersion: z.literal(CLUB_DATA_EXPORT_FORMAT_VERSION),
    createdAt: dateTimeSchema,
    startedAt: dateTimeSchema.nullable(),
    completedAt: dateTimeSchema.nullable(),
  })
  .meta({ id: 'ClubDataExport' });

export type ClubDataExport = z.output<typeof clubDataExportSchema>;

const exportParams = z.strictObject({ exportId: clubDataExportIdSchema });

const ACCESS =
  'La pide la administración (todo el club) o el preparador físico (`sc`, sus categorías asignadas); cada uno ve las suyas y la administración, todas las del club. El superadmin de soporte no exporta datos de un club.';

export const createClubDataExport = defineEndpoint({
  method: 'POST',
  path: '/v1/data-exports',
  summary: 'Exportar los datos del club en CSV',
  description: `Registra el pedido y lo deja \`queued\`; el sistema genera un ZIP con un CSV por conjunto (formato es-AR: \`;\` entre campos, coma decimal, \`dd/mm/aaaa\`, UTF-8 con BOM), un diccionario de columnas y un manifiesto, y lo deja para bajar 7 días. ${ACCESS} Incluye a los jugadores/as del alcance con consentimiento de datos vigente; nunca datos de salud (solo la disponibilidad del día, sin el motivo). El alcance y la disponibilidad se fijan al pedir. Idempotente por \`clientUuid\`: el mismo con otro pedido es \`conflict\`.`,
  tags: ['exports'],
  auth: 'club',
  body: z
    .strictObject({
      clientUuid: clientUuidSchema.optional(),
      datasets: z
        .array(clubDataExportDatasetSchema)
        .min(1)
        .max(CLUB_DATA_EXPORT_DATASETS.length)
        .optional()
        .meta({
          description: 'Conjuntos a incluir; todos si se omite.',
        }),
      from: localDateSchema.optional(),
      to: localDateSchema.optional(),
    })
    .refine((body) => clubDataExportRangeProblems(body).length === 0, {
      message: '`from` is after `to`',
      path: ['from'],
    }),
  response: { status: 202, description: 'Pedido registrado.', schema: clubDataExportSchema },
  errors: ['conflict', 'service_unavailable'],
});

export const listClubDataExports = defineEndpoint({
  method: 'GET',
  path: '/v1/data-exports',
  summary: 'Exportaciones de datos',
  description: ACCESS,
  tags: ['exports'],
  auth: 'club',
  query: pageQuerySchema.extend({
    sort: sortQuerySchema(['createdAt'], '-createdAt'),
  }),
  response: {
    status: 200,
    description: 'Página de exportaciones.',
    schema: pageOf(clubDataExportSchema).meta({ id: 'ClubDataExportPage' }),
  },
  errors: ['bad_request'],
});

export const getClubDataExport = defineEndpoint({
  method: 'GET',
  path: '/v1/data-exports/{exportId}',
  summary: 'Una exportación de datos',
  description: `Su estado (para esperar a que esté \`ready\`). ${ACCESS} Ajena o de otro club: \`not_found\`.`,
  tags: ['exports'],
  auth: 'club',
  params: exportParams,
  response: { status: 200, description: 'La exportación.', schema: clubDataExportSchema },
  errors: ['not_found'],
});

export const getClubDataExportDownload = defineEndpoint({
  method: 'GET',
  path: '/v1/data-exports/{exportId}/download',
  summary: 'Bajar una exportación de datos',
  description: `URL firmada de vida corta (minutos) del ZIP (\`${FILE_KIND_POLICIES.data_export.contentTypes[0]}\`, \`attachment\`). Solo de una exportación \`ready\` (si no, o si venció: \`conflict\`). ${ACCESS}`,
  tags: ['exports'],
  auth: 'club',
  params: exportParams,
  response: { status: 200, description: 'URL de descarga.', schema: fileDownloadSchema },
  errors: ['not_found', 'conflict', 'service_unavailable'],
});
