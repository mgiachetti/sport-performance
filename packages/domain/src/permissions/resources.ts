export type ResourceKind = keyof typeof PERMISSION_RESOURCES;
export type ResourceTarget = (typeof PERMISSION_RESOURCES)[ResourceKind]['target'];
/** Actions of one resource kind. */
export type ActionOf<K extends ResourceKind> = (typeof PERMISSION_RESOURCES)[K]['actions'][number];
/** Every action of every kind. */
export type PermissionAction = { [K in ResourceKind]: ActionOf<K> }[ResourceKind];

export const RESOURCE_KINDS = Object.keys(PERMISSION_RESOURCES) as ResourceKind[];

export function isResourceKind(value: unknown): value is ResourceKind {
  return typeof value === 'string' && Object.hasOwn(PERMISSION_RESOURCES, value);
}

export function actionsOf<K extends ResourceKind>(kind: K): readonly ActionOf<K>[] {
  return PERMISSION_RESOURCES[kind].actions;
}

export function isActionOf<K extends ResourceKind>(kind: K, value: unknown): value is ActionOf<K> {
  return typeof value === 'string' && actionsOf(kind).some((action) => action === value);
}
