/**
 * What the permission matrix protects (B-303, ADR 0025): a closed set of
 * resource kinds, each with its own closed set of actions.
 *
 * `target` says what a resource instance identifies, which is what the
 * evaluator needs to place it in a scope:
 *
 * - `platform`: nothing inside a club (the registry of clubs).
 * - `club`: the club as a whole (settings, catalogs, users).
 * - `category`: a category of the club (sessions, test days); the request
 *   passes the category, or a player when it is about one player.
 * - `player`: one player (profile, results, consents, health); the request
 *   passes the player.
 *
 * `medical` resources live in the `medical` schema (ADR 0008): every allowed
 * access carries the `audit_medical_access` obligation.
 *
 * Adding a kind or an action does not compile until every role has a rule in
 * `PERMISSION_MATRIX` and fails the tests until the cell has a specification.
 */
