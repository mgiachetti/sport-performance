import { describe, expect, it } from 'vitest';
import {
  CLUB_DATA_EXPORT_DATASETS,
  CLUB_DATA_EXPORT_FILE_NAMES,
  clubDataExportFileName,
  clubDataExportRangeProblems,
  isDatedClubDataExportDataset,
  normalizeClubDataExportDatasets,
  parseClubDataExportDataset,
} from './club-data-export.js';
import { FILE_KIND_POLICIES } from './files.js';
import { parseLocalDate } from './time.js';

describe('club data export', () => {
  it('names one distinct CSV per dataset', () => {
    const names = CLUB_DATA_EXPORT_DATASETS.map((d) => CLUB_DATA_EXPORT_FILE_NAMES[d]);
    expect(new Set(names).size).toBe(names.length);
    for (const name of names) expect(name).toMatch(/^[a-z_]+\.csv$/);
  });

  it('parses only known datasets', () => {
    expect(parseClubDataExportDataset('wellness')).toBe('wellness');
    expect(() => parseClubDataExportDataset('medical')).toThrow(/dataset/);
  });

  it('normalizes the requested datasets to the canonical order, all by default', () => {
    expect(normalizeClubDataExportDatasets(undefined)).toEqual([...CLUB_DATA_EXPORT_DATASETS]);
    expect(normalizeClubDataExportDatasets([])).toEqual([...CLUB_DATA_EXPORT_DATASETS]);
    expect(normalizeClubDataExportDatasets(['wellness', 'players', 'wellness'])).toEqual([
      'players',
      'wellness',
    ]);
  });

  it('only filters by date the datasets with a club day', () => {
    expect(isDatedClubDataExportDataset('wellness')).toBe(true);
    expect(isDatedClubDataExportDataset('players')).toBe(false);
    expect(isDatedClubDataExportDataset('metrics')).toBe(false);
  });

  it('rejects a range that ends before it starts', () => {
    const d = parseLocalDate;
    expect(clubDataExportRangeProblems({})).toEqual([]);
    expect(clubDataExportRangeProblems({ from: d('2026-03-01') })).toEqual([]);
    expect(clubDataExportRangeProblems({ from: d('2026-03-01'), to: d('2026-03-01') })).toEqual([]);
    expect(clubDataExportRangeProblems({ from: d('2026-03-02'), to: d('2026-03-01') })).toEqual([
      'from_after_to',
    ]);
  });

  it('names the ZIP with the club slug and the ISO day', () => {
    expect(clubDataExportFileName('orc', parseLocalDate('2026-11-03'))).toBe(
      'datos-orc-2026-11-03.zip',
    );
    expect(clubDataExportFileName('Olivos RC!', parseLocalDate('2026-11-03'))).toBe(
      'datos-olivos-rc-2026-11-03.zip',
    );
    expect(clubDataExportFileName('---', parseLocalDate('2026-11-03'))).toBe(
      'datos-club-2026-11-03.zip',
    );
  });

  it('keeps the ZIP a week, as an attachment generated by the server', () => {
    expect(FILE_KIND_POLICIES.data_export).toMatchObject({
      contentTypes: ['application/zip'],
      subject: 'club',
      retention: { kind: 'days', days: 7 },
      disposition: 'attachment',
      clientUpload: false,
    });
  });
});
