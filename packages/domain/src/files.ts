import { memberGuard, memberParser } from './enum.js';
import { DomainValidationError } from './errors.js';
import type { ClubId, Uuid } from './ids.js';

/**
 * Uploaded files (B-325, ADR 0044). The bytes live in the S3-compatible
 * bucket (ADR 0003), never in Postgres nor through the API; the `file` table
 * keeps what the file is, whose it is and until when it is kept.
 *
 * `packages/db` builds the `file_kind` and `file_status` enums from these
 * constants, so a value is never renamed.
 */

/**
 * What a file is. Each kind has its own policy ({@link FILE_KIND_POLICIES}):
 * - `club_logo`: the crest of the club (white-label theme, ADR 0014).
 * - `cmj_video`: high-speed video of a countermovement jump (B-604): an image
 *   of a player, shown and uploaded only with a current image consent.
 * - `pdf_report`: report of a player for a test window (B-602), generated by
 *   the worker.
 * - `data_import`: a spreadsheet to import (roster B-330, Catapult B-601).
 * - `protocol_media`: an image or video that shows how a test is done, attached
 *   to a protocol version (B-415, ADR 0067). Staff only: it may show a person.
 */
export const FILE_KINDS = [
  'club_logo',
  'cmj_video',
  'pdf_report',
  'data_import',
  'protocol_media',
] as const;
export type FileKind = (typeof FILE_KINDS)[number];
export const isFileKind = memberGuard(FILE_KINDS);
export const parseFileKind = memberParser(FILE_KINDS, 'invalid_argument', 'file kind');

/**
 * Life of a file: `pending` (row created, upload URL handed out, bytes not
 * confirmed), `ready` (the bucket holds exactly the declared bytes) and
 * `deleted` (expired or deleted on request; the row stays as a record, the
 * object is purged from the bucket).
 */
export const FILE_STATUSES = ['pending', 'ready', 'deleted'] as const;
export type FileStatus = (typeof FILE_STATUSES)[number];
export const isFileStatus = memberGuard(FILE_STATUSES);
export const parseFileStatus = memberParser(FILE_STATUSES, 'invalid_argument', 'file status');

/** What a file of a kind belongs to, besides the club. */
export type FileSubject = 'club' | 'player' | 'category_optional';

/**
 * How long a file is kept once confirmed.
 * - `days`: deleted `days` after it was confirmed.
 * - `while_in_use`: kept while something points at it (the crest of the
 *   club, the media of a protocol); once nothing does, deleted `unusedDays`
 *   later.
 */
export type FileRetention =
  | { readonly kind: 'days'; readonly days: number }
  | { readonly kind: 'while_in_use'; readonly unusedDays: number };

export interface FileKindPolicy {
  /** MIME types accepted, lowercase, without parameters. */
  readonly contentTypes: readonly [string, ...string[]];
  /** Largest file, in bytes. */
  readonly maxSizeBytes: number;
  readonly subject: FileSubject;
  readonly retention: FileRetention;
  /** Downloads open in place (`inline`) or are saved (`attachment`). */
  readonly disposition: 'inline' | 'attachment';
  /**
   * Whether clients upload it with a signed URL. `pdf_report` is written by
   * the worker (B-602), never uploaded by a person.
   */
  readonly clientUpload: boolean;
}

const MIB = 1024 * 1024;

/**
 * Policy of each kind (ADR 0044). Retention follows data minimization (Ley
 * 25.326): a CMJ video is evidence to review the jump, the height stays in
 * the result; a report is regenerated from the data; an import is only
 * needed to audit what was imported.
 */
export const FILE_KIND_POLICIES = {
  club_logo: {
    // Raster only: an SVG can carry scripts and the crest is served inline (ADR 0044).
    contentTypes: ['image/png', 'image/webp'],
    maxSizeBytes: 1 * MIB,
    subject: 'club',
    retention: { kind: 'while_in_use', unusedDays: 30 },
    disposition: 'inline',
    clientUpload: true,
  },
  cmj_video: {
    // iOS records QuickTime, Android MP4 (react-native-vision-camera, B-604).
    contentTypes: ['video/mp4', 'video/quicktime'],
    maxSizeBytes: 250 * MIB,
    subject: 'player',
    retention: { kind: 'days', days: 180 },
    disposition: 'inline',
    clientUpload: true,
  },
  pdf_report: {
    contentTypes: ['application/pdf'],
    maxSizeBytes: 20 * MIB,
    subject: 'player',
    retention: { kind: 'days', days: 365 },
    disposition: 'attachment',
    clientUpload: false,
  },
  data_import: {
    contentTypes: [
      'text/csv',
      'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
      'application/vnd.ms-excel',
    ],
    maxSizeBytes: 20 * MIB,
    subject: 'category_optional',
    retention: { kind: 'days', days: 90 },
    disposition: 'attachment',
    clientUpload: true,
  },
  protocol_media: {
    // Raster images and web video only: never SVG (scripts) nor formats a browser
    // does not play inline. Short clips of how the test is done, not match footage.
    contentTypes: ['image/png', 'image/jpeg', 'image/webp', 'video/mp4', 'video/webm'],
    maxSizeBytes: 100 * MIB,
    subject: 'club',
    retention: { kind: 'while_in_use', unusedDays: 30 },
    disposition: 'inline',
    clientUpload: true,
  },
} as const satisfies Record<FileKind, FileKindPolicy>;

/** Kinds a client uploads with a signed URL. */
export const CLIENT_UPLOAD_FILE_KINDS = FILE_KINDS.filter(
  (kind) => FILE_KIND_POLICIES[kind].clientUpload,
) as readonly ClientUploadFileKind[];
export type ClientUploadFileKind = {
  [K in FileKind]: (typeof FILE_KIND_POLICIES)[K]['clientUpload'] extends true ? K : never;
}[FileKind];

/** An upload not confirmed within this window is purged with whatever reached the bucket. */
export const PENDING_UPLOAD_RETENTION_HOURS = 24;

/** Longest caption of a protocol image or video: its text alternative (B-415). */
export const PROTOCOL_MEDIA_CAPTION_MAX_LENGTH = 200;

/** Longest original file name kept (shown on download). */
export const FILE_NAME_MAX_LENGTH = 200;

/** SHA-256 of the content, base64 (`x-amz-checksum-sha256`): 32 bytes, 44 characters. */
export const SHA256_BASE64_PATTERN = /^[A-Za-z0-9+/]{43}=$/;

const DAY_MS = 24 * 60 * 60 * 1000;
const HOUR_MS = 60 * 60 * 1000;

/** The problems of a declared upload against the policy of its kind; empty when it fits. */
export function fileUploadProblems(input: {
  readonly kind: FileKind;
  readonly contentType: string;
  readonly sizeBytes: number;
}): ('content_type' | 'size')[] {
  const policy: FileKindPolicy = FILE_KIND_POLICIES[input.kind];
  const problems: ('content_type' | 'size')[] = [];
  if (!policy.contentTypes.includes(input.contentType)) problems.push('content_type');
  if (
    !Number.isSafeInteger(input.sizeBytes) ||
    input.sizeBytes < 1 ||
    input.sizeBytes > policy.maxSizeBytes
  ) {
    problems.push('size');
  }
  return problems;
}

/** Until when a pending upload created at `createdAt` may be confirmed. */
export function pendingUploadExpiresAt(createdAt: Date): Date {
  return new Date(createdAt.getTime() + PENDING_UPLOAD_RETENTION_HOURS * HOUR_MS);
}

/**
 * Longest life of a signed upload URL (`FILE_UPLOAD_URL_TTL_S` is at most
 * this): a URL signed at any moment is valid at most this long, whatever
 * the configuration was when it was signed.
 */
export const FILE_UPLOAD_URL_MAX_TTL_S = 3600;

/**
 * Margin of the retention job over `expires_at`: the bucket checks a signed
 * URL with its own clock, which may lag the API's.
 */
export const SIGNED_URL_CLOCK_SKEW_S = 300;

/**
 * `expires_at` of a file deleted on request at `now`: the moment after which
 * no upload URL ever handed out for it can still be honored. The job that
 * removes the object must not run before a late `PUT` could land: whatever
 * it removed would come back, untracked. Upload URLs are only signed while
 * the file is `pending`, for at most {@link FILE_UPLOAD_URL_MAX_TTL_S} and
 * never past its upload window, so they are all dead by:
 * - pending: the end of the window, or `now` + the longest URL if sooner;
 * - confirmed: `uploadedAt` + the longest URL (one signed just before the
 *   confirmation may still be valid); `now` if nobody uploaded it;
 * - never before `now`. The job adds {@link SIGNED_URL_CLOCK_SKEW_S}.
 */
export function deletedFileExpiresAt(
  file: {
    readonly status: FileStatus;
    readonly expiresAt: Date | null;
    readonly uploadedAt: Date | null;
  },
  now: Date,
): Date {
  const maxUrlMs = FILE_UPLOAD_URL_MAX_TTL_S * 1000;
  let urlsValidUntil = now.getTime();
  if (file.status === 'pending') {
    const latestUrl = now.getTime() + maxUrlMs;
    urlsValidUntil =
      file.expiresAt === null ? latestUrl : Math.min(file.expiresAt.getTime(), latestUrl);
  } else if (file.uploadedAt !== null) {
    urlsValidUntil = file.uploadedAt.getTime() + maxUrlMs;
  }
  return new Date(Math.max(now.getTime(), urlsValidUntil));
}

/**
 * When a file confirmed at `confirmedAt` is deleted. `inUse` only matters
 * for `while_in_use` kinds: in use it never expires (`null`); otherwise it
 * expires `unusedDays` after `confirmedAt` (pass the moment it stopped
 * being used).
 */
export function fileExpiresAt(kind: FileKind, confirmedAt: Date, inUse = false): Date | null {
  const retention: FileRetention = FILE_KIND_POLICIES[kind].retention;
  switch (retention.kind) {
    case 'days':
      return new Date(confirmedAt.getTime() + retention.days * DAY_MS);
    case 'while_in_use':
      return inUse ? null : new Date(confirmedAt.getTime() + retention.unusedDays * DAY_MS);
  }
}

/**
 * Key of a file's object in the bucket: `clubs/<club>/<kind>/<file>`. The
 * club leads the key (ADR 0005): tenant isolation also holds in storage,
 * and a club's objects can be listed, exported or removed together.
 */
export function fileObjectKey(file: {
  readonly clubId: ClubId;
  readonly kind: FileKind;
  readonly id: Uuid | string;
}): string {
  return `clubs/${file.clubId}/${file.kind}/${file.id}`;
}

/**
 * A file name that is safe in a `Content-Disposition` header and on any
 * file system: no path, no control characters, at most
 * {@link FILE_NAME_MAX_LENGTH} characters. Throws on an empty result.
 */
export function sanitizeFileName(name: string): string {
  const base = name.split(/[\\/]/).at(-1) ?? '';
  // Every Unicode control character (C0, DEL and C1 such as U+0085): what the
  // database's `[[:cntrl:]]` rejects under a UTF-8 locale.
  const cleaned = base.replace(/[\p{Cc}"]/gu, '').trim();
  if (cleaned === '' || cleaned === '.' || cleaned === '..') {
    throw new DomainValidationError('invalid_argument', 'Invalid file name', name);
  }
  // By code points, like `char_length` in the database (never splits a surrogate pair).
  return Array.from(cleaned).slice(0, FILE_NAME_MAX_LENGTH).join('').trimEnd();
}
